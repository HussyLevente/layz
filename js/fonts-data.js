  function fallbackFor(cat) {
    if (cat === 'serif') return 'Georgia, serif';
    if (cat === 'mono') return 'ui-monospace, monospace';
    if (cat === 'handwriting') return 'cursive';
    if (cat === 'display') return 'system-ui, sans-serif';
    return 'system-ui, -apple-system, sans-serif';
  }

  /* unpack the 9-bit mask into real weight numbers */
  function weightsOf(mask) {
    var out = [];
    for (var i = 0; i < 9; i++) {
      if (mask & (1 << i)) { out.push((i + 1) * 100); }
    }
    return out.length ? out : [400];
  }

