  /* nearest weight a family actually has - never request one it lacks */
  function nearestWeight(font, want) {
    var ws = font.weights, best = ws[0], diff = Math.abs(ws[0] - want);
    for (var i = 1; i < ws.length; i++) {
      var d = Math.abs(ws[i] - want);
      if (d < diff) { diff = d; best = ws[i]; }
    }
    return best;
  }

